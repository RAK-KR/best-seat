"""4편 자동 플레이"""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'shared'))
from playtest_core import Tester
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
t = Tester(ROOT, sys.argv[1], sys.argv[2], 'ep4/index.html')
z7 = -2.6 + 6 * 0.62
t.goto(1.6, 3.5); t.aim(1.6, 1.6, 4.34); t.use('notice', '02_notice')
t.goto(0.0, 1.9); t.aim(0.66, 0.62, z7); t.use('row7', '03_row7')
t.goto(0.2, z7); t.aim(1.94, 0.74, z7); t.use('seat9')
t.goto(4.15, z7); t.aim(2.46, 0.55, z7); t.use('seat10')
t.check('boothKey' in t.state('inv'), '영사실 열쇠')
t.shot('04_hall')
t.goto(1.6, 3.6); t.aim(1.6, 1.0, 4.4); t.use('boothDoor'); t.wait(900)
t.check(t.state('boothOpen'), '영사실 열림')
t.goto(1.2, 5.3); t.aim(2.15, 1.4, 4.95); t.use('power')
t.check(t.state('power'), '전원')
t.goto(-0.9, 6.0); t.aim(-1.82, 0.84, 5.95); t.use('log', '05_log')
t.aim(-1.8, 0.88, 6.5); t.use('tickets', '06_tickets')
t.goto(1.0, 6.3); t.aim(1.98, 0.9, 6.3); t.use('cans', '07_cans', close=False)
t.btn(0); t.check('reel' not in t.state('inv'), '광고 릴은 아님'); t.btn(2)
t.check('reel' in t.state('inv'), '금요일 릴'); t.esc()
t.goto(0.9, 5.3); t.aim(0.2, 1.9, 5.1); t.use('projector', close=False)
t.btn(0); t.check(t.state('mounted'), '릴 걸림')
t.btn(1); t.wait(800); t.lock()
t.check(t.state('running'), '영사기 돌아감')
t.shot('08_booth')
t.goto(0.0, 0.0); t.aim(0, 2.3, -4.95)
for _ in range(40):
    if t.state('k.k_footage') == True: break
    t.wait(1000)
t.wait(2000); t.shot('09_screen')
t.check(t.state('k.k_footage') == True, '스크린의 필름을 봄')
t.goto(0.2, z7); t.aim(1.42, 0.5, z7); t.use('seat8', close=False); t.wait(600)
t.keys('1500'); t.check(not t.state('canOpen'), '1500은 오답')
