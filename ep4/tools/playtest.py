t.check(t.state('canOpen'), '1315로 깡통 열림')
t.shot('10_can'); t.btn(0); t.shot('11_negative'); t.btn(0); t.shot('12_letter'); t.esc()
t.goto(-4.1, 3.6); t.aim(-4.47, 1.0, 3.65); t.use('entrance')
t.wait(5000); t.check(t.state('done'), '극장을 나섬'); t.shot('13_ending')
t.pg.mouse.click(640, 200); t.wait(800); t.shot('14_ending_all', True)
t.end()
